/**
 * Builds backend/src/ai/catalog/search-catalog.data.ts from the frontend
 * brand/model lists the /cars filters actually offer.
 * Run: node scripts/build-search-catalog.cjs
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..');
const catalogPath = path.join(root, 'frontend/src/features/addItem/constants/vehicleCatalog.ts');
const optionsPath = path.join(root, 'frontend/src/vehicles/components/AutoSearchFilter/options.js');

const catalogSrc = fs.readFileSync(catalogPath, 'utf8');
const brandsBlock = catalogSrc.slice(
  catalogSrc.indexOf('export const CAR_BRANDS'),
  catalogSrc.indexOf('export type CarBrand'),
);
const modelsBlock = catalogSrc.slice(
  catalogSrc.indexOf('export const CAR_MODELS'),
  catalogSrc.indexOf('const trimKey'),
);
const catalogFn = new Function(
  `${brandsBlock.replace('export const ', 'const ').replace(' as const', '')}\n${modelsBlock
    .replace('export const ', 'const ')
    .replace(': Record<string, string[]>', '')}\nreturn { CAR_BRANDS, CAR_MODELS };`,
);
const { CAR_BRANDS, CAR_MODELS } = catalogFn();

const optionsSrc = fs
  .readFileSync(optionsPath, 'utf8')
  .replace(/export const /g, 'const ');
const { makesByCategory, modelsByMake } = new Function(
  `${optionsSrc}\nreturn { makesByCategory, modelsByMake };`,
)();

const brands = [
  ...new Set([
    ...CAR_BRANDS,
    ...makesByCategory.car.filter((brand) => brand !== 'All Makes'),
  ]),
].sort((a, b) => a.localeCompare(b));

const models = {};
for (const brand of brands) {
  const merged = [
    ...new Set([...(CAR_MODELS[brand] ?? []), ...(modelsByMake[brand] ?? [])]),
  ].sort((a, b) => a.localeCompare(b));
  if (merged.length) models[brand] = merged;
}

const out = `/* Generated by backend/scripts/build-search-catalog.cjs. Do not edit by hand. */
export const SEARCH_BRANDS: string[] = ${JSON.stringify(brands, null, 2)};

export const SEARCH_MODELS: Record<string, string[]> = ${JSON.stringify(models, null, 2)};
`;

const dest = path.join(__dirname, '..', 'src/ai/catalog/search-catalog.data.ts');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log('brands', brands.length, 'with models', Object.keys(models).length);
